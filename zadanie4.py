#Задаём список 
spisok = [12, 4, 9, 1, 6, 3]
#Создаём главную функцию для рекурсивной сортировки слиянием
def merge_sort(spisok):
    #В случае если в списке 1 элемент или список пуст то
    if len(spisok) <= 1:
        #возвращаем этот список
        return spisok
    #Находим индекс элемента по середине
    mid = len(spisok) // 2
    #Рекурсивно запускаем сортировку для левой части
    left = merge_sort(spisok[:mid])
    #Аналогично для правой  
    right = merge_sort(spisok[mid:])
    #Загоняем наши две части в один список
    return merge(left, right)
#Теперь создаем функцию для обьединения двух отсортированных списков в один
def merge(left, right):
    #Создаем пустой список в котором мы будем сортировать элементы в правильном порядке
    sposok = []
    #Задаём начало нашиъ двух списков что бы сравнивать числа с самого начала
    i = j = 0
    #Задаём цикл который будет выполняться пока не проверятся все элементы
    while i < len(left) and j < len(right):
        #Если элемент из левого списка больше чем элемент правого
        if left[i] > right[j]:  
            #То добавляем в наш новый список больший элемент из левого 
            sposok.append(left[i])
            #И сдвигаем наш маркер вправо на 1
            i += 1
        #В пративном случаи
        else:
            #Добавляем в наш новый список больший элемент из правого
            sposok.append(right[j])
            #И сдвигаем наш маркер вправо на 1
            j += 1
    #Добавляем оставшиеся элементы из левого списка 
    sposok.extend(left[i:])
    #Добавляем оставшиеся элементы из правого списка 
    sposok.extend(right[j:])
    #Возвращаем готовый отсртированный список (убывающий)
    return sposok
#Вывоим наш отсортированный список\
print(merge_sort(spisok))