#Задаем список из чисел
spisok = [2,5,8,11,14,18,21,25,30]
#Вводим число с клавиатуры для поиска в списке
chislo = int(input('Введите число '))
#Задем левую границу поиска
first = 0
#Задаем прувую границу поиска(от длины списка в нашем случае это 9 эл )
last = len(spisok)-1
#задаём переменную в которой будет хранится наш ответ в случае не нахождения числа
i = -1
#Запускаем цикл который бкдет выполняться пока лева граница не пересечет правую или на оборот
while (first <= last):
    #Находим элемент стоящий по середине нашего списка
    mid = (first+last)//2
    #Если средний элемент списка равен нашему элементу 
    if spisok[mid] == chislo:
        #То присваиваем индекс числа посередине нашему числу
        i = mid
        #И заканчиваем цикл
        break
    #В противоположном случаи
    else:
        #Если наше число меньше числа из середины списка
        if chislo<spisok[mid]:
            #Значит сдвигаем правую грань в лево так как числа находится левее 
            last = mid -1
        #Или же
        else:
            #Число больше чем средний элемент и мы двигаем левуую грань в про 
            first = mid +1
#Таким образом цикл будет отнимать элементы слеа или справа пока наш элемент не сравняется с элементом по середине
# И в этом случае выводлим индекс элемента которы равен нашему числу 
print(i)
#Ну а в противном случаи если цикл не найдет элемент то выведится -1