#Задаём список 
spisok = [29, 10, 14, 37, 13]
#Задаем езщё один список в который мы будем добавлять отсортированные элементы
sortirovka = []
#Запускаем цикл который работает до тех пр пока в списке не отсанется элементов
while len(spisok) > 0:
    #Берем самый первый элемет нашего списка и считаем его минимальным
    min = spisok[0]
    #Перебираем все элементы нашего списка
    for i in range(0, len(spisok)):
        #Если мы находим элемент меньший чем наш заданный минимум раньше (который являеся первым элементом)
        if spisok[i] < min:
            #То обновляем значение наименьшего элемента
            min = spisok[i]
    #Добовляем наш минимальный элемент в пустой список
    sortirovka.append(min)
    #И удаляем его из старого
    spisok.remove(min)
    #И выводим наш получившийся список
    print(sortirovka)
#После добавления и удаления минимального элемента который мы нашли путем манипуляй выше, значение минимального(первого) элемента 
#обновляется и уикл прогоняет таким образом все элементы и у нас получается отсортированный по возрастанию список