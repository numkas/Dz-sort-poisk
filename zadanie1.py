#Создаем список участников кружка
spisok = ['Анна', 'Иваг', 'Мария', 'Олег']
#Делаем ввод с калвиатуры имя которое нам нужно проверить
imy = input('Введите имя ')
#Делаем условие через in  что если введенное имя пренадлежит нашему списку 
if imy in spisok:
    #Выводим что имя пренадлежит списку
    print('Участник найден')
#В пративном случае
else:
    #Выводим что не принадлежит
    print('Участник не найден')
